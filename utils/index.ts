export const getStateFromGSTIN = (gstin: string) => {
  if (gstin && gstin.length >= 2) {
    const code = gstin.substring(0, 2);
    return GST_STATE_CODE_MAP[code] || "";
  }
  return "";
};

export const validateGSTIN = (gstin: string) => {
  const gstinRegex = /^[0-9]{2}[A-Z]{5}[0-9]{4}[A-Z]{1}[1-9A-Z]{1}Z[0-9A-Z]{1}$/;
  return gstinRegex.test(gstin.toUpperCase());
};

export const validatePAN = (pan: string) => {
  const panRegex = /^[A-Z]{5}[0-9]{4}[A-Z]{1}$/;
  return panRegex.test(pan.toUpperCase());
};

export const extractPANFromGSTIN = (gstin: string) => {
  if (gstin.length >= 12) {
    return gstin.substring(2, 12).toUpperCase();
  }
  return "";
};